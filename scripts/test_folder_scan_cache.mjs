import assert from 'node:assert/strict';
import fs from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const url=new URL('../desktop/src/services/folder_scan_cache.ts',import.meta.url);
const retention=new URL('../desktop/src/services/scan_retention.ts',import.meta.url);
const source=stripTypeScriptTypes(fs.readFileSync(url,'utf8')).replace("'./scan_retention'",JSON.stringify(retention.href));
const {FolderScanCache}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
let now=0;const cache=new FolderScanCache(()=>now,3);
cache.put(['/parent'],{id:'parent'},1);cache.put(['/parent/child'],{id:'child'},1);
assert.equal(cache.get('/parent',1).id,'parent');assert.equal(cache.get('/parent/child',1).id,'child');
assert.equal(cache.get('/new',1),undefined);now=300000;assert.equal(cache.get('/parent',1),undefined);
cache.put(['/a'],1,1);assert.equal(cache.get('/a',2),undefined);
cache.put(['/a'],1,2);cache.put(['/b'],2,2);cache.put(['/c'],3,2);cache.get('/a',2);cache.put(['/d'],4,2);assert.equal(cache.get('/b',2),undefined);
cache.clear();assert.equal(cache.get('/a',2),undefined);
cache.put(['~/','/home'],5,3);assert.equal(cache.get('/home',3),5);
console.log('PASS: parent/child reuse, new folder miss, TTL, mutation revision, LRU bound, explicit refresh, canonical alias');

let queries=0;
const readRetained=async(ticket,path)=>{queries++;return ticket==='snapshot'&&path==='/root/large/deep'?{path,oldFiles:50050}:null;};
cache.clear();now=0;
assert.equal((await cache.resolve('/root/large/deep',8,'snapshot',readRetained)).oldFiles,50050);
assert.equal(queries,1);
assert.equal((await cache.resolve('/root/large/deep',8,'snapshot',readRetained)).oldFiles,50050);
assert.equal(queries,1,'visited folder reads frontend cache without another host query');
assert.equal(await cache.resolve('/outside',8,'snapshot',readRetained),undefined);
assert.equal(await cache.resolve('/root/new',8,'',readRetained),undefined);
assert.equal(queries,2,'missing ticket does not scan or query');
now=300000;await cache.resolve('/root/large/deep',8,'snapshot',readRetained);assert.equal(queries,3);
cache.clear();await cache.resolve('/root/large/deep',9,'snapshot',readRetained);assert.equal(queries,4);
console.log('PASS: first-visit deep folder reads Rust snapshot, visited reuse, outside miss, no scan inside loader, TTL and mutation invalidation');
